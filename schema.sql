-- Each entrant's total live points = sum(votes * pick.multiplier) for their picked players
create or replace view entrant_totals as
select
  e.id as entrant_id,
  e.name,
  coalesce(sum(bv.votes * p.multiplier), 0) as total_points
from entrants e
left join picks p on p.entrant_id = e.id
left join brownlow_votes bv on bv.afl_player_id = p.afl_player_id
group by e.id, e.name;

-- Draft board: static picks table, ordered by pick_number
create or replace view draft_board as
select
  p.pick_number,
  p.round,
  e.draft_position,
  e.name as entrant_name,
  ap.full_name as player_name,
  ap.team,
  p.multiplier
from picks p
join entrants e on e.id = p.entrant_id
join afl_players ap on ap.id = p.afl_player_id
order by p.pick_number;
